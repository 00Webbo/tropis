// Package devcorpus generates the synthetic development corpus from the
// scenario definitions.
//
// Every fixture it produces is marked synthetic and must never be published:
// fixture.PublishableCorpus refuses them. The corpus exists so the eval
// runner, scoring and report can be built and tested before the rig exists,
// and so prompt and backend changes have something to run against in CI.
//
// It is deliberately built from the same scenario definitions as the real
// capture plan, and emits genuine smartctl -j and Kubernetes API shapes, so
// replay exercises the real SMART parser and input builder.
package devcorpus

