const (
	nodeName   = "worker-02"
	device     = "/dev/sdb"
	serial     = "DEVCORPUS0001"
	diskModel  = "Synthetic HDD 2TB"
	mountpoint = "/mnt/disks/sacrificial"
)

// base is the capture time of the first scenario; each subsequent scenario is
// an hour later. Fixed, so generation is deterministic.
var base = time.Date(2026, 9, 1, 0, 0, 0, 0, time.UTC)

// Generate writes one fixture.json and label.json per scenario per NPD
// variant under dir, replacing whatever is there.
func Generate(dir string, all []scenarios.Scenario) error {
	if err := os.RemoveAll(dir); err != nil {
		return err
	}
	for i, s := range all {
		at := base.Add(time.Duration(i) * time.Hour)
		for _, variant := range []schema.Variant{schema.VariantNPDAbsent, schema.VariantNPDPresent} {
			f, err := fixtureFor(s, variant, at)
			if err != nil {
				return fmt.Errorf("%s: %w", s.ID, err)
			}
			l := s.Label()
			l.Notes = "SYNTHETIC development fixture, not captured from hardware. " + l.Notes
			if err := f.Validate(); err != nil {
				return fmt.Errorf("%s/%s: generated an invalid fixture: %w", s.ID, variant, err)
			}
			if err := l.Validate(); err != nil {
				return fmt.Errorf("%s: invalid label: %w", s.ID, err)
			}
			out := filepath.Join(dir, s.ID+"-"+string(variant))
			if err := writeJSON(filepath.Join(out, "fixture.json"), f); err != nil {
				return err
			}
			if err := writeJSON(filepath.Join(out, "label.json"), l); err != nil {
				return err
			}
		}
	}
	return os.WriteFile(filepath.Join(dir, "README.md"), []byte(readme), 0o644)
}

const readme = `# Development corpus — NOT PUBLISHABLE

Every fixture here is **synthetic**: generated by eval/devcorpus from
eval/scenarios/scenarios.yaml, not captured from hardware. Each is marked
"synthetic": true, and fixture.PublishableCorpus refuses to load them.

They exist to build and test the eval runner, scoring and report before the
capture rig exists. Accuracy numbers computed against this corpus say nothing
about Tropis and must never be published or quoted.

Regenerate with ` + "`go run ./hack/gen-devcorpus`" + `. A test fails if this
directory drifts from the scenario definitions.
`

func writeJSON(path string, v any) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(b, '\n'), 0o644)
}

func fixtureFor(s scenarios.Scenario, variant schema.Variant, at time.Time) (*schema.Fixture, error) {
	current, previous, transport, err := smartFor(s.Synthetic.SMART, at)
	if err != nil {
		return nil, err
	}
	k, alerts, k8sgpt, err := workloadFor(s, at)
	if err != nil {
		return nil, err
	}

	f := &schema.Fixture{
		Version:    schema.FixtureVersion,
		ScenarioID: s.ID,
		Variant:    variant,
		CapturedAt: at,
		Node:       nodeName,
		Environment: schema.Environment{
			Kernel:            "6.8.0-45-generic",
			OSRelease:         "Ubuntu 24.04.1 LTS",
			KubernetesVersion: "v1.31.2",
			ContainerRuntime:  "containerd://1.7.22",
			DiskModel:         diskModel,
			DiskTransport:     transport,
			NPDPresent:        variant == schema.VariantNPDPresent,
		},
		Host: schema.HostCapture{
			SMART:       map[string]schema.RawJSON{device: current},
			CollectedAt: at,
		},
		Kubernetes: k,
		Baseline:   schema.Baseline{PrometheusAlerts: alerts, K8sGPTOutput: k8sgpt},
		Synthetic:  true,
	}
	if previous != nil {
		f.Host.Previous = &schema.HostSnapshot{
			SMART:       map[string]schema.RawJSON{device: previous},
			CollectedAt: at.Add(-24 * time.Hour),
		}
	}
	if variant == schema.VariantNPDPresent {
		f.Kubernetes.NPDConditions = npdConditions(s.Synthetic.NPD, at)
		f.Environment.NPDVersion = "v0.8.20"
	}
	return f, nil
}

